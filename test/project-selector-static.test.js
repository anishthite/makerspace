import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');

test('project selector offers desktop local folders', () => {
  const pages = read('frontend/src/pages.jsx');
  const project = read('frontend/src/runtime/project.js');
  const settingsJs = read('frontend/src/runtime/settings.js');
  const styles = read('frontend/public/styles.css');
  const app = read('frontend/src/runtime/app.js');

  assert.match(pages, /project-choose-folder/);
  assert.match(pages, /choose local folder/i);
  assert.match(pages, /className="project-target repo-input repo-combobox"[\s\S]*project-choose-folder/);
  assert.match(pages, /id="project-repo-options" className="repo-suggestions" role="listbox" hidden/);
  assert.doesNotMatch(pages, /project-repo-picker/);
  assert.match(pages, /id="project-status" className="status-line" aria-live="polite"><\/p>/);
  assert.doesNotMatch(pages, /project-provider-banner/);
  assert.match(project, /const repoOptions = document\.querySelector\('#project-repo-options'\)/);
  assert.match(project, /const repoTray = document\.querySelector\('#project-repo-tray'\)/);
  assert.match(project, /repoTray\.hidden = local && canChooseFolder/);
  assert.match(project, /spannerDesktop\?\.chooseFolder/);
  assert.match(project, /spannerSelectedProject/);
  assert.match(project, /\/api\/recent-projects/);
  assert.match(project, /project-running-badge/);
  assert.match(project, /function filterRepos\(query/);
  assert.match(project, /function renderRepoSuggestions\(\)/);
  assert.match(project, /repoInput\.addEventListener\('keydown'/);
  assert.match(project, /cache: 'no-store'/);
  assert.match(project, /function refreshProjectThreads\(\)/);
  assert.match(project, /await refreshProjectThreads\(\);[\s\S]+await loadGitHubRepos\(\);/);
  assert.match(project, /function effectiveThreadStatus\(thread\)/);
  assert.match(project, /runningAgentCount/);
  assert.match(pages, /href="\/settings\.html#codex"/);
  assert.match(pages, /href="\/settings\.html#github"/);
  assert.match(pages, /id="github-signin-card"/);
  assert.match(pages, /Continue with GitHub/);
  assert.match(pages, /data-github-signin/);
  assert.match(pages, /className=\{`signin-gate/);
  assert.match(project, /function startGitHubSignIn/);
  assert.match(project, /\/api\/auth\/github\/login/);
  assert.match(project, /renderGitHubSignIn\(github\)/);
  assert.match(project, /projectGrid\.hidden = showGate/);
  assert.match(app, /function startGitHubSignIn/);
  assert.match(app, /renderGitHubSignIn\(status\)/);
  assert.match(app, /threadForm\.hidden = showGate/);
  assert.match(styles, /\.signin-gate \{[^}]*grid-template-columns: minmax\(0, 1\.05fr\) minmax\(280px, \.7fr\)/);
  assert.match(pages, /id="codex"/);
  assert.match(pages, /id="claude-code"/);
  assert.match(pages, /id="github"/);
  assert.match(settingsJs, /function openWebCodexTab\(\)/);
  assert.match(settingsJs, /function navigateCodexTab\(codexTab, url\)/);
  assert.match(settingsJs, /function openWebClaudeCodeTab\(\)/);
  assert.match(settingsJs, /\/api\/auth\/claude-code/);
  assert.match(settingsJs, /globalThis\.open\?\.\('about:blank', '_blank'\)/);
  assert.match(styles, /\.home-actions \.auth-pill \{[^}]*border-color: transparent;/);
  assert.match(styles, /\.project-shell \{[^}]*width: min\(900px, calc\(100% - clamp\(40px, 12vw, 280px\)\)\)/);
  assert.match(styles, /\.project-grid \{[^}]*grid-template-columns: 1fr/);
  assert.match(styles, /#project-form \{[^}]*display: grid;[^}]*gap: 12px;/);
  assert.match(styles, /\.repo-suggestions \{/);
  assert.match(styles, /\.project-card \.repo-tray \{[^}]*display: flex;/);
  assert.match(app, /readSelectedProject/);
  assert.match(app, /repoPath: repoInput/);
});
