import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');

test('project selector offers desktop local folders', () => {
  const pages = read('frontend/src/pages.jsx');
  const project = read('frontend/src/runtime/project.js');
  const settingsJs = read('frontend/src/runtime/settings.js');
  const styles = read('frontend/src/styles/app.css');
  const app = read('frontend/src/runtime/app.js');

  assert.match(pages, /project-choose-folder/);
  assert.match(pages, /choose local folder/i);
  assert.match(pages, /id="project-repo-url"[\s\S]*project-choose-folder/);
  assert.match(pages, /id="project-repo-options" className="repo-suggestions[^"]*" role="listbox" hidden/);
  assert.doesNotMatch(pages, /project-repo-picker/);
  assert.match(pages, /id="project-status" className=\{statusLineClass\} aria-live="polite"><\/p>/);
  assert.doesNotMatch(pages, /project-provider-banner/);
  assert.match(project, /const repoOptions = document\.querySelector\('#project-repo-options'\)/);
  assert.match(project, /const repoTray = document\.querySelector\('#project-repo-tray'\)/);
  assert.match(project, /repoTray\.hidden = local && canChooseFolder/);
  assert.match(project, /spannerDesktop\?\.chooseFolder/);
  assert.match(project, /spannerSelectedProject/);
  assert.match(project, /\/api\/recent-projects/);
  assert.match(project, /project-running-badge/);
  assert.match(project, /function filterRepos\(query/);
  assert.match(project, /function renderRepoSuggestions\(\)/);
  assert.match(project, /repoInput\.addEventListener\('keydown'/);
  assert.match(project, /cache: 'no-store'/);
  assert.match(project, /function refreshProjectThreads\(\)/);
  assert.match(project, /function loadProjectBootstrap\(\)/);
  assert.match(project, /\/api\/bootstrap\?page=project/);
  assert.match(project, /void loadGitHubRepos\(\)\.catch/);
  assert.match(project, /function effectiveThreadStatus\(thread\)/);
  assert.match(project, /runningAgentCount/);
  assert.match(pages, /href="\/settings\.html#codex"/);
  assert.match(pages, /href="\/settings\.html#github"/);
  assert.match(pages, /id="github-signin-card"/);
  assert.match(pages, /Continue with GitHub/);
  assert.match(pages, /data-github-signin/);
  assert.match(pages, /id="github-signin-card" className=\{cn\(surfaceClass/);
  assert.match(project, /function startGitHubSignIn/);
  assert.match(project, /\/api\/auth\/github\/login/);
  assert.match(project, /renderGitHubSignIn\(github\)/);
  assert.match(project, /const desktop = Boolean\(globalThis\.spannerDesktop\);[\s\S]+const showGate = !desktop && providerKind !== 'local'/);
  assert.match(project, /button\.hidden = desktop \|\| providerKind === 'local'/);
  assert.match(project, /projectGrid\.hidden = showGate/);
  assert.match(app, /function startGitHubSignIn/);
  assert.match(app, /function loadWorkspaceBootstrap\(\)/);
  assert.match(app, /\/api\/bootstrap\?page=workspace/);
  assert.match(app, /renderGitHubSignIn\(status\)/);
  assert.match(app, /const desktop = Boolean\(globalThis\.spannerDesktop\);[\s\S]+const showGate = !desktop && !localProvider/);
  assert.match(app, /button\.hidden = desktop \|\| localProvider/);
  assert.match(app, /threadForm\.hidden = showGate/);
  assert.match(pages, /md:grid-cols-\[minmax\(0,1\.05fr\)_minmax\(280px,\.7fr\)\]/);
  assert.match(pages, /id="codex"/);
  assert.match(pages, /id="claude-code"/);
  assert.match(pages, /id="github"/);
  assert.match(pages, /id="codex-device-dialog"/);
  assert.match(pages, /id="codex-device-copy"/);
  assert.match(pages, /id="claude-code-dialog"/);
  assert.match(pages, /id="claude-code-open"/);
  assert.match(pages, /id="claude-code-copy-link"/);
  assert.match(settingsJs, /const codexDeviceDialog = document\.querySelector\('#codex-device-dialog'\)/);
  assert.match(settingsJs, /const claudeCodeDialog = document\.querySelector\('#claude-code-dialog'\)/);
  assert.match(settingsJs, /const claudeCodeCopyLink = document\.querySelector\('#claude-code-copy-link'\)/);
  assert.match(settingsJs, /function openAuthDialog\(dialog, statusTarget/);
  assert.match(settingsJs, /function resetCodexDeviceDialog\(\)/);
  assert.match(settingsJs, /function resetClaudeCodeDialog\(\)/);
  assert.match(settingsJs, /navigator\.clipboard\?\.writeText/);
  assert.match(settingsJs, /setAuthLink\(codexDeviceOpen, verificationUri\)/);
  assert.doesNotMatch(settingsJs, /function openWebCodexTab/);
  assert.doesNotMatch(settingsJs, /navigateCodexTab/);
  assert.doesNotMatch(settingsJs, /function openWebClaudeCodeTab\(\)/);
  assert.match(settingsJs, /\/api\/auth\/claude-code/);
  assert.match(settingsJs, /Paste the code Claude showed/);
  assert.match(pages, /id="claude-code-paste"/);
  assert.match(styles, /\.auth-steps \{/);
  assert.doesNotMatch(settingsJs, /globalThis\.open\?\.\('about:blank', '_blank'\)/);
  assert.match(pages, /const pill = 'group inline-flex/);
  assert.match(pages, /w-\[min\(980px,calc\(100%_-_clamp\(32px,10vw,240px\)\)\)\]/);
  assert.match(pages, /id="project-grid" className="mx-auto mt-\[clamp\(42px,8vh,92px\)\] grid max-w-\[820px\] grid-cols-1 gap-4"/);
  assert.match(pages, /id="project-form" className=\{cn\(surfaceClass, 'grid gap-5 overflow-hidden p-5 md:p-6'\)\}/);
  assert.match(pages, /id="project-hero" className="grid gap-2 text-left/);
  assert.match(styles, /\.repo-suggestions \{/);
  assert.match(pages, /id="project-repo-tray" className="flex flex-wrap items-center gap-2"/);
  assert.match(app, /readSelectedProject/);
  assert.match(app, /repoPath: repoInput/);
});
