import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const html = readFileSync(new URL('../frontend/desktop.html', import.meta.url), 'utf8');
const pages = readFileSync(new URL('../frontend/src/pages.jsx', import.meta.url), 'utf8');
const runtime = readFileSync(new URL('../frontend/src/runtime/desktop.js', import.meta.url), 'utf8');
const entry = readFileSync(new URL('../frontend/src/entry.jsx', import.meta.url), 'utf8');
const design = readFileSync(new URL('../DESIGN.md', import.meta.url), 'utf8');

test('desktop landing is a React route with GitHub sign-in behavior', () => {
  assert.match(html, /data-react-page="desktop"/);
  assert.match(html, /src="\/src\/entry\.jsx"/);
  assert.match(pages, /function DesktopLandingPage\(\)/);
  assert.match(pages, /landing-brand-mark/);
  assert.match(pages, /src="\/logo-mark\.svg"/);
  assert.match(pages, /id="signin-open"/);
  assert.match(pages, /data-open-signin/);
  assert.match(pages, />Get Started<\/button>/);
  assert.doesNotMatch(pages, /Open a Pi sandbox/);
  assert.match(pages, /<GitHubSignInCard \/>/);
  assert.doesNotMatch(pages, /<dialog id="signin-modal"/);
  assert.doesNotMatch(pages, /modal-proof|signin-close|github-button/);
  assert.match(pages, /data-landing-agent-loop/);
  assert.match(pages, /data-landing-agent-prompt/);
  assert.match(pages, /\.landing-agent-loop/);
  assert.match(pages, /running agents/);
  assert.doesNotMatch(pages, /3–4 active/);
  assert.doesNotMatch(pages, /landing-agent-loop::before/);
  assert.match(pages, /Continue with GitHub/);
  assert.match(runtime, /function startAgentLoop/);
  assert.match(runtime, /function startPromptComposer/);
  assert.match(runtime, /finished · evidence ready/);
  assert.match(runtime, /prefers-reduced-motion/);
  assert.match(runtime, /\/api\/auth\/github['"]/);
  assert.match(runtime, /\/api\/auth\/github\/login/);
  assert.match(runtime, /VITE_SPANNER_API_BASE/);
  assert.match(runtime, /'x-spanner-session': sessionId\(\)/);
  assert.match(runtime, /function targetUrl\(\)/);
  assert.match(runtime, /querySelectorAll\('\[data-open-signin\]'\)/);
  assert.match(runtime, /querySelector\('#github-signin-card'\)/);
  assert.match(runtime, /querySelector\('#github-signin-main'\)/);
  assert.match(runtime, /function setSignInOpen\(open\)/);
  assert.match(runtime, /openButtons\.forEach/);
  assert.doesNotMatch(runtime, /signin-modal|signin-close|openModal/);
  assert.match(runtime, /JSON\.stringify\(\{ returnTo: targetUrl\(\) \}\)/);
  assert.match(entry, /desktop: \(\) => import\('\.\/runtime\/desktop\.js'\)/);
});

test('desktop landing follows the root design system and Roughdraft guide', () => {
  assert.match(design, /# Spanner design system/);
  assert.match(design, /`accent` \| `#1F5E9C`/);
  assert.match(pages, /Design source: roughdraft\.md \+ DESIGN\.md/);
  assert.match(pages, /--ds-bg:var\(--bg,#050607\)/);
  assert.match(pages, /--ds-accent:var\(--blue,#8CBDFD\)/);
  assert.doesNotMatch(pages, /landing-eyebrow|landing-kicker/);
  assert.match(pages, /Easier remote coding/);
  assert.match(pages, /aria-label="Spanner review workspace"/);
  assert.match(pages, /className="landing-workflow-grid"/);
  assert.match(pages, /\.landing-shot, \.landing-workflow, \.landing-proof, \.landing-footer \{ display:none; \}/);
  assert.match(pages, /It is still Markdown/);
  assert.match(pages, /className="landing-proof-grid"/);
});
