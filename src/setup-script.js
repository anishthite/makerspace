import { gzipSync } from 'node:zlib';

function shellQuote(value) {
  const escaped = String(value).replace(/'/g, `'\\''`);
  return `'${escaped}'`;
}

function buildRepoLines(session, config) {
  const workspaceDir = config.remoteWorkspaceDir;

  if (session.repoMode === 'git') {
    const gitArgs = ['git'];

    if (session.repoAuthHeader) {
      gitArgs.push('-c', shellQuote(`http.extraHeader=${session.repoAuthHeader}`));
    }

    const plainClone = [
      ...gitArgs,
      'clone',
      '--depth=1',
      shellQuote(session.repoUrl),
      shellQuote(workspaceDir),
    ].join(' ');

    if (session.branch) {
      const branchClone = [
        ...gitArgs,
        'clone',
        '--depth=1',
        '--branch',
        shellQuote(session.branch),
        shellQuote(session.repoUrl),
        shellQuote(workspaceDir),
      ].join(' ');
      return [
        'export GIT_TERMINAL_PROMPT=0',
        `rm -rf ${shellQuote(workspaceDir)}`,
        `${branchClone} || { rm -rf ${shellQuote(workspaceDir)}; ${plainClone}; }`,
        `cd ${shellQuote(workspaceDir)}`,
      ];
    }

    return [
      'export GIT_TERMINAL_PROMPT=0',
      `rm -rf ${shellQuote(workspaceDir)}`,
      plainClone,
      `cd ${shellQuote(workspaceDir)}`,
    ];
  }

  const initBranch = shellQuote(session.branch || 'main');
  return [
    `mkdir -p ${shellQuote(workspaceDir)}`,
    `cd ${shellQuote(workspaceDir)}`,
    'if [ ! -d .git ]; then',
    '  git init',
    `  git branch -M ${initBranch} || true`,
    `  printf '# %s\\n' ${shellQuote(session.name)} > README.md`,
    'fi',
  ];
}

function wrapBase64(value, width = 120) {
  const lines = [];

  for (let index = 0; index < value.length; index += width) {
    lines.push(value.slice(index, index + width));
  }

  return lines;
}

function buildCompressedFileLines(filePath, content) {
  const encoded = gzipSync(Buffer.from(content, 'utf8')).toString('base64');

  return [
    `cat <<'EOF' | base64 -d | gzip -d > ${shellQuote(filePath)}`,
    ...wrapBase64(encoded),
    'EOF',
  ];
}

function buildBridgeScriptSource(session, config) {
  const remoteHomeDir = config.remoteHomeDir || '/home/daytona';
  const bridgePackageDir = `${remoteHomeDir}/.pi/agent/npm`;
  const authDir = `${remoteHomeDir}/.pi/agent`;
  const authPath = `${authDir}/auth.json`;

  return [
    "import http from 'node:http';",
    "import { createWriteStream } from 'node:fs';",
    "import { chmod, mkdir, writeFile } from 'node:fs/promises';",
    "import crypto from 'node:crypto';",
    "import path from 'node:path';",
    "import { pathToFileURL } from 'node:url';",
    '',
    `const port = Number(process.env.PI_BRIDGE_PORT || ${JSON.stringify(String(config.bridgePort || 4310))});`,
    `const token = process.env.PI_BRIDGE_TOKEN || ${JSON.stringify(session.bridgeToken || '')};`,
    `const controlDir = process.env.PI_BRIDGE_CONTROL_DIR || ${JSON.stringify(config.remoteControlDir)};`,
    `const workspaceDir = process.env.PI_BRIDGE_WORKSPACE_DIR || ${JSON.stringify(config.remoteWorkspaceDir)};`,
    `const sessionDir = process.env.PI_CODING_AGENT_SESSION_DIR || path.join(controlDir, 'pi-sessions');`,
    `const bridgePackageDir = process.env.PI_BRIDGE_PACKAGE_DIR || ${JSON.stringify(bridgePackageDir)};`,
    `const authDir = ${JSON.stringify(authDir)};`,
    `const authPath = ${JSON.stringify(authPath)};`,
    'const runs = new Map();',
    'let sdkModulePromise = null;',
    'let piSessionPromise = null;',
    '',
    'function sendJson(response, statusCode, payload) {',
    "  response.writeHead(statusCode, { 'content-type': 'application/json; charset=utf-8' });",
    '  response.end(`${JSON.stringify(payload, null, 2)}\\n`);',
    '}',
    '',
    'async function readJsonBody(request) {',
    '  let text = "";',
    '  for await (const chunk of request) text += chunk;',
    '  return text.trim() ? JSON.parse(text) : {};',
    '}',
    '',
    'function isAuthorized(request) {',
    "  if ((request.url || '').startsWith('/healthz')) return true;",
    '  if (!token) return false;',
    "  const header = request.headers.authorization || '';",
    "  return header === `Bearer ${token}`;",
    '}',
    '',
    'function writeSse(response, payload) {',
    '  response.write(`data: ${JSON.stringify(payload)}\\n\\n`);',
    '}',
    '',
    'function textFromContent(content) {',
    '  if (!Array.isArray(content)) return "";',
    '  return content',
    '    .map((part) => {',
    '      if (!part || typeof part !== "object") return "";',
    '      if (part.type === "text") return String(part.text || "");',
    '      return "";',
    '    })',
    '    .join("");',
    '}',
    '',
    'function resultText(result) {',
    '  return textFromContent(result?.content);',
    '}',
    '',
    'function formatToolLabel(event) {',
    '  if (event.toolName === "bash" && event.args && typeof event.args.command === "string") {',
    '    const firstLine = event.args.command.split(/\\r?\\n/)[0]?.trim() || "bash";',
    '    return `bash: ${firstLine.slice(0, 120)}`;',
    '  }',
    '  return String(event.toolName || "tool");',
    '}',
    '',
    'async function loadSdk() {',
    '  if (!sdkModulePromise) {',
    '    const entry = path.join(bridgePackageDir, "node_modules", "@earendil-works", "pi-coding-agent", "dist", "index.js");',
    '    sdkModulePromise = import(pathToFileURL(entry).href);',
    '  }',
    '  return sdkModulePromise;',
    '}',
    '',
    'async function createPiSession() {',
    '  const { createAgentSession, SessionManager } = await loadSdk();',
    '  return createAgentSession({',
    '    cwd: workspaceDir,',
    '    sessionManager: SessionManager.inMemory(workspaceDir),',
    '  });',
    '}',
    '',
    'function preparePiSession() {',
    '  if (!piSessionPromise) {',
    '    piSessionPromise = createPiSession().catch((error) => {',
    '      piSessionPromise = null;',
    '      throw error;',
    '    });',
    '  }',
    '  return piSessionPromise;',
    '}',
    '',
    'function ensureRun(id) {',
    '  let run = runs.get(id);',
    '  if (!run) {',
    '    run = {',
    '      id,',
    "      status: 'queued',",
    '      createdAt: new Date().toISOString(),',
    '      updatedAt: new Date().toISOString(),',
    '      output: "",',
    '      index: 0,',
    '      events: [],',
    '      clients: new Set(),',
    '      child: null,',
    '      logStream: null,',
    '      exitCode: null,',
    '      submittedAtMs: null,',
    '    };',
    '    runs.set(id, run);',
    '  }',
    '  return run;',
    '}',
    '',
    'function publish(run, event) {',
    '  const payload = {',
    '    index: ++run.index,',
    '    runId: run.id,',
    '    timestamp: new Date().toISOString(),',
    '    ...event,',
    '  };',
    '  run.updatedAt = payload.timestamp;',
    '  if (payload.chunk) {',
    '    run.output += payload.chunk;',
    '    if (run.logStream) run.logStream.write(payload.chunk);',
    '  }',
    '  if (payload.runStatus) run.status = payload.runStatus;',
    '  if (Object.prototype.hasOwnProperty.call(payload, "exitCode")) run.exitCode = payload.exitCode;',
    '  run.events.push(payload);',
    '  if (run.events.length > 2000) run.events.shift();',
    '  for (const client of run.clients) {',
    '    writeSse(client, payload);',
    '  }',
    '  if (payload.done) {',
    '    for (const client of run.clients) client.end();',
    '    run.clients.clear();',
    '  }',
    '  return payload;',
    '}',
    '',
    'async function startRun(run, prompt, name, submittedAtMs) {',
    '  const normalizedSubmittedAtMs = Number(submittedAtMs);',
    '  run.submittedAtMs = Number.isFinite(normalizedSubmittedAtMs) && normalizedSubmittedAtMs > 0 ? normalizedSubmittedAtMs : null;',
    '  await mkdir(controlDir, { recursive: true });',
    '  await mkdir(sessionDir, { recursive: true });',
    '  const logFilePath = path.join(controlDir, `${run.id}.log`);',
    '  run.logStream = createWriteStream(logFilePath, { flags: "a" });',
    "  publish(run, { type: 'status', runStatus: 'starting' });",
    '  run.child = {};',
    '  let unsubscribe = null;',
    '  let piSession = null;',
    '  let firstProviderCallPublished = false;',
    '  const toolOutput = new Map();',
    '  let streamedAssistantText = "";',
    '  let agentDoneResolve = null;',
    '  const agentDonePromise = new Promise((resolve) => { agentDoneResolve = resolve; });',
    '',
    '  try {',
    '    const created = await preparePiSession();',
    '    piSession = created.session;',
    '    const originalStreamFn = piSession.agent.streamFn;',
    '    piSession.agent.streamFn = (...args) => {',
    '      if (!firstProviderCallPublished) {',
    '        firstProviderCallPublished = true;',
    '        const nowMs = Date.now();',
    '        const latencyMs = run.submittedAtMs ? nowMs - run.submittedAtMs : null;',
    '        publish(run, {',
    '          type: "metric",',
    '          metric: "first_llm_call_start",',
    '          runStatus: "running",',
    '          latencyMs,',
    '          submittedAtMs: run.submittedAtMs,',
    '          firstLlmCallStartedAtMs: nowMs,',
    '        });',
    '      }',
    '      return originalStreamFn(...args);',
    '    };',
    '    unsubscribe = piSession.subscribe((event) => {',
    '      if (event.type === "message_update" && event.assistantMessageEvent.type === "text_delta") {',
    '        streamedAssistantText += event.assistantMessageEvent.delta;',
    '        publish(run, { type: "stdout", chunk: event.assistantMessageEvent.delta, runStatus: "running" });',
    '        return;',
    '      }',
    '',
    '      if (event.type === "tool_execution_start") {',
    '        publish(run, {',
    '          type: "tool",',
    '          phase: "start",',
    '          toolCallId: event.toolCallId,',
    '          label: formatToolLabel(event),',
    '        });',
    '        return;',
    '      }',
    '',
    '      if (event.type === "tool_execution_update") {',
    '        const nextText = resultText(event.partialResult);',
    '        const previousText = toolOutput.get(event.toolCallId) || "";',
    '        const delta = nextText.startsWith(previousText) ? nextText.slice(previousText.length) : nextText;',
    '        toolOutput.set(event.toolCallId, nextText);',
    '        if (delta) {',
    '          publish(run, {',
    '            type: "tool",',
    '            phase: "update",',
    '            toolCallId: event.toolCallId,',
    '            label: formatToolLabel(event),',
    '            delta,',
    '          });',
    '        }',
    '        return;',
    '      }',
    '',
    '      if (event.type === "agent_end") {',
    '        if (agentDoneResolve) agentDoneResolve();',
    '        const messages = Array.isArray(event.messages) ? event.messages : Array.isArray(event.newMessages) ? event.newMessages : [];',
    '        const assistant = [...messages].reverse().find((message) => message?.role === "assistant");',
    '        const finalText = textFromContent(assistant?.content);',
    '        if (finalText && !streamedAssistantText.trim()) {',
    '          streamedAssistantText = finalText;',
    '          publish(run, { type: "stdout", chunk: finalText, runStatus: "running" });',
    '        }',
    '        return;',
    '      }',
    '',
    '      if (event.type === "tool_execution_end") {',
    '        publish(run, {',
    '          type: "tool",',
    '          phase: "end",',
    '          toolCallId: event.toolCallId,',
    '          label: formatToolLabel(event),',
    '          isError: Boolean(event.isError)',
    '        });',
    '      }',
    '    });',
    "    publish(run, { type: 'status', runStatus: 'running' });",
    '    await piSession.prompt(prompt);',
    '    await agentDonePromise;',
    '    const lastAssistantText = piSession.getLastAssistantText?.();',
    '    if (lastAssistantText && !streamedAssistantText.trim()) {',
    '      publish(run, { type: "stdout", chunk: lastAssistantText, runStatus: "running" });',
    '    }',
    '    if (!streamedAssistantText.trim() && !lastAssistantText) {',
    '      throw new Error("Pi completed without assistant output. Check remote provider auth.");',
    '    }',
    '    publish(run, { type: "status", runStatus: "completed", done: true, exitCode: 0 });',
    '  } catch (error) {',
    '    publish(run, {',
    '      type: "status",',
    '      runStatus: "failed",',
    '      warning: error.message,',
    '      done: true,',
    '      exitCode: 1,',
    '    });',
    '  } finally {',
    '    if (typeof unsubscribe === "function") unsubscribe();',
    '    if (piSession) piSession.dispose();',
    '    piSessionPromise = null;',
    '    run.child = null;',
    '    if (run.logStream) {',
    '      run.logStream.end();',
    '      run.logStream = null;',
    '    }',
    '  }',
    '}',
    '',
    'const server = http.createServer(async (request, response) => {',
    '  try {',
    '    const url = new URL(request.url || "/", `http://${request.headers.host || "127.0.0.1"}`);',
    '    if (!isAuthorized(request)) {',
    '      sendJson(response, 401, { error: "Unauthorized" });',
    '      return;',
    '    }',
    '',
    '    if (request.method === "GET" && url.pathname === "/healthz") {',
    '      sendJson(response, 200, { ok: true, running: [...runs.values()].filter((run) => run.status === "running").length });',
    '      return;',
    '    }',
    '',
    '    if (request.method === "POST" && url.pathname === "/auth") {',
    '      const body = await readJsonBody(request);',
    '      const authText = String(body.authText || "");',
    '      const settingsText = String(body.settingsText || "");',
    '      if (!authText && !settingsText) {',
    '        sendJson(response, 400, { error: "authText or settingsText is required." });',
    '        return;',
    '      }',
    '      await mkdir(authDir, { recursive: true });',
    '      if (authText) {',
    '        await writeFile(authPath, authText, "utf8");',
    '        await chmod(authPath, 0o600);',
    '      }',
    '      if (settingsText) {',
    '        await writeFile(path.join(authDir, "settings.json"), settingsText, "utf8");',
    '        await chmod(path.join(authDir, "settings.json"), 0o600);',
    '      }',
    '      if (piSessionPromise) {',
    '        try {',
    '          const warmed = await piSessionPromise;',
    '          warmed.session?.dispose?.();',
    '        } catch {}',
    '        piSessionPromise = null;',
    '      }',
    '      void preparePiSession().catch(() => {});',
    '      sendJson(response, 200, { ok: true });',
    '      return;',
    '    }',
    '',
    '    if (request.method === "POST" && url.pathname === "/runs") {',
    '      const body = await readJsonBody(request);',
    '      const prompt = String(body.prompt || "").trim();',
    '      const requestedId = String(body.id || crypto.randomUUID());',
    '      const name = String(body.name || requestedId).trim() || requestedId;',
    '      const submittedAtMs = Number(body.submittedAtMs);',
    '      if (!prompt) {',
    '        sendJson(response, 400, { error: "Prompt is required." });',
    '        return;',
    '      }',
    '      const active = [...runs.values()].find((run) => run.child);',
    '      if (active && active.id !== requestedId) {',
    '        sendJson(response, 409, { error: `Run ${active.id} is still running.` });',
    '        return;',
    '      }',
    '      const run = ensureRun(requestedId);',
    '      if (!run.child && run.events.length === 0) {',
    "        publish(run, { type: 'status', runStatus: 'queued' });",
    '        void startRun(run, prompt, name, submittedAtMs);',
    '      }',
    '      sendJson(response, 202, { id: run.id, status: run.status });',
    '      return;',
    '    }',
    '',
    '    const runMatch = url.pathname.match(/^\\/runs\\/([^/]+)$/);',
    '    if (request.method === "GET" && runMatch) {',
    '      const run = runs.get(decodeURIComponent(runMatch[1]));',
    '      if (!run) {',
    '        sendJson(response, 404, { error: "Run not found." });',
    '        return;',
    '      }',
    '      sendJson(response, 200, { id: run.id, status: run.status, exitCode: run.exitCode });',
    '      return;',
    '    }',
    '',
    '    const streamMatch = url.pathname.match(/^\\/runs\\/([^/]+)\\/stream$/);',
    '    if (request.method === "GET" && streamMatch) {',
    '      const run = runs.get(decodeURIComponent(streamMatch[1]));',
    '      if (!run) {',
    '        sendJson(response, 404, { error: "Run not found." });',
    '        return;',
    '      }',
    '      const after = Number(url.searchParams.get("after"));',
    '      const normalizedAfter = Number.isFinite(after) && after > 0 ? after : 0;',
    '      response.writeHead(200, {',
    '        "content-type": "text/event-stream; charset=utf-8",',
    '        "cache-control": "no-cache, no-transform",',
    '        connection: "keep-alive",',
    '      });',
    '      response.write("retry: 1000\\n\\n");',
    '      for (const event of run.events) {',
    '        if (event.index > normalizedAfter) writeSse(response, event);',
    '      }',
    '      if (run.status === "completed" || run.status === "failed") {',
    '        response.end();',
    '        return;',
    '      }',
    '      run.clients.add(response);',
    '      request.on("close", () => {',
    '        run.clients.delete(response);',
    '      });',
    '      return;',
    '    }',
    '',
    '    sendJson(response, 404, { error: "Not found." });',
    '  } catch (error) {',
    '    sendJson(response, 500, { error: error.message });',
    '  }',
    '});',
    '',
    'server.listen(port, "0.0.0.0", () => {',
    '  console.log(`[pi-bridge] listening on ${port}`);',
    '});',
  ].join('\n');
}

export function buildSetupScript(session, config) {
  const controlDir = config.remoteControlDir;
  const workspaceDir = config.remoteWorkspaceDir;
  const taskPrompt = session.taskPrompt || config.defaultTaskPrompt;
  const taskPromptB64 = Buffer.from(taskPrompt, 'utf8').toString('base64');
  const logPath = `${controlDir}/pi.log`;
  const taskPath = `${controlDir}/TASK.md`;
  const runScriptPath = `${controlDir}/run-pi.sh`;
  const howToPath = `${controlDir}/HOWTO.txt`;
  const statusPath = `${controlDir}/STATUS`;
  const sessionDir = `${controlDir}/pi-sessions`;
  const bridgeEnvPath = `${controlDir}/bridge-env.sh`;
  const bridgeScriptPath = `${controlDir}/pi-bridge.mjs`;
  const bridgeStartPath = `${controlDir}/start-bridge.sh`;
  const bridgeServicePath = '/etc/systemd/system/pi-bridge.service';
  const bridgePort = String(config.bridgePort || 4310);
  const remoteUser = config.remoteUser || 'daytona';
  const remoteHomeDir = config.remoteHomeDir || `/home/${remoteUser}`;
  const bridgePackageDir = `${remoteHomeDir}/.pi/agent/npm`;
  const aptPackages = ['git', 'curl', 'ca-certificates'];
  const aptCommands = ['git', 'curl'];

  if (session.autoRunAgent && !session.bridgeMode) {
    aptPackages.push('tmux');
    aptCommands.push('tmux');
  }

  const lines = [
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    'if [ "$(id -u)" -ne 0 ]; then exec sudo -E /bin/bash "$0" "$@"; fi',
    '',
    'export DEBIAN_FRONTEND=noninteractive',
    'missing_apt=0',
    `for cmd in ${aptCommands.map(shellQuote).join(' ')}; do`,
    '  command -v "$cmd" >/dev/null 2>&1 || missing_apt=1',
    'done',
    'if [ "$missing_apt" -eq 1 ]; then',
    '  apt-get update',
    `  apt-get install -y ${aptPackages.map(shellQuote).join(' ')}`,
    'fi',
    'if ! command -v node >/dev/null 2>&1 || ! command -v npm >/dev/null 2>&1; then',
    '  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -',
    '  apt-get install -y nodejs',
    'fi',
    'if ! command -v pi >/dev/null 2>&1; then',
    `  ${config.piInstallCommand}`,
    'fi',
    'installed_bridge_sdk=0',
    `if [ ! -d ${shellQuote(`${bridgePackageDir}/node_modules/@earendil-works/pi-coding-agent`)} ]; then`,
    '  PI_VERSION="$(pi --version | tr -d "[:space:]")"',
    `  PI_SDK_SPEC=${shellQuote('@earendil-works/pi-coding-agent')}`,
    '  if [ -n "$PI_VERSION" ]; then',
    '    PI_SDK_SPEC="${PI_SDK_SPEC}@${PI_VERSION}"',
    '  fi',
    `  mkdir -p ${shellQuote(bridgePackageDir)}`,
    `  npm install --prefix ${shellQuote(bridgePackageDir)} --no-audit --no-fund --ignore-scripts --legacy-peer-deps "$PI_SDK_SPEC"`,
    '  installed_bridge_sdk=1',
    'fi',
    `mkdir -p ${shellQuote(controlDir)} ${shellQuote(workspaceDir)} ${shellQuote(sessionDir)}`,
    `printf '%s\\n' booting > ${shellQuote(statusPath)}`,
    ...buildRepoLines(session, config),
    `printf '%s' ${shellQuote(taskPromptB64)} | base64 -d > ${shellQuote(taskPath)}`,
    `: > ${shellQuote(bridgeEnvPath)}`,
    `printf 'export HOME=%s\\n' ${shellQuote(remoteHomeDir)} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PATH=%s\\n' ${shellQuote(`${remoteHomeDir}/.local/bin:/usr/local/bin:/usr/bin:/bin`)} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PI_CODING_AGENT_SESSION_DIR=%s\\n' ${shellQuote(sessionDir)} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PI_SKIP_VERSION_CHECK=%s\\n' ${shellQuote('1')} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PI_BRIDGE_PORT=%s\\n' ${shellQuote(bridgePort)} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PI_BRIDGE_TOKEN=%s\\n' ${shellQuote(session.bridgeToken || '')} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PI_BRIDGE_CONTROL_DIR=%s\\n' ${shellQuote(controlDir)} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PI_BRIDGE_WORKSPACE_DIR=%s\\n' ${shellQuote(workspaceDir)} >> ${shellQuote(bridgeEnvPath)}`,
    `printf 'export PI_BRIDGE_PACKAGE_DIR=%s\\n' ${shellQuote(bridgePackageDir)} >> ${shellQuote(bridgeEnvPath)}`,
  ];

  for (const key of config.forwardEnvKeys || []) {
    lines.push(`printf 'export ${key}=%q\\n' "\${${key}:-}" >> ${shellQuote(bridgeEnvPath)}`);
  }

  lines.push(
    `cat > ${shellQuote(runScriptPath)} <<'SH'`,
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    `source ${shellQuote(bridgeEnvPath)}`,
    `mkdir -p ${shellQuote(sessionDir)}`,
    `cd ${shellQuote(workspaceDir)}`,
    `PROMPT_TEXT="$(cat ${shellQuote(taskPath)})"`,
    `printf '%s\\n' running > ${shellQuote(statusPath)}`,
    `if pi --approve --name ${shellQuote(session.name)} -p "$PROMPT_TEXT"; then`,
    `  printf '%s\\n' completed > ${shellQuote(statusPath)}`,
    'else',
    '  code=$?',
    `  printf '%s\\n' failed > ${shellQuote(statusPath)}`,
    '  exit "$code"',
    'fi',
    'SH',
    `chmod +x ${shellQuote(runScriptPath)}`,
    ...buildCompressedFileLines(bridgeScriptPath, buildBridgeScriptSource(session, config)),
    `chmod +x ${shellQuote(bridgeScriptPath)}`,
    `cat > ${shellQuote(bridgeStartPath)} <<'SH'`,
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    `source ${shellQuote(bridgeEnvPath)}`,
    `mkdir -p ${shellQuote(sessionDir)}`,
    `cd ${shellQuote(workspaceDir)}`,
    `exec node ${shellQuote(bridgeScriptPath)}`,
    'SH',
    `chmod +x ${shellQuote(bridgeStartPath)}`,
    `cat > ${shellQuote(bridgeServicePath)} <<'UNIT'`,
    '[Unit]',
    'Description=pi bridge',
    'After=network-online.target',
    '',
    '[Service]',
    'Type=simple',
    `User=${remoteUser}`,
    `Group=${remoteUser}`,
    `WorkingDirectory=${workspaceDir}`,
    `ExecStart=${bridgeStartPath}`,
    'Restart=always',
    'RestartSec=2',
    '',
    '[Install]',
    'WantedBy=multi-user.target',
    'UNIT',
    `cat > ${shellQuote(howToPath)} <<'TXT'`,
    `Connect to the sandbox and run: bash ${runScriptPath}`,
    `Bridge health: curl http://127.0.0.1:${bridgePort}/healthz`,
    `Bridge logs: journalctl -u pi-bridge -n 120 --no-pager || tail -n 120 ${controlDir}/pi-bridge.log`,
    `Log tail: tail -n 120 ${logPath}`,
    'TXT',
    `if id ${shellQuote(remoteUser)} >/dev/null 2>&1; then chown -R ${shellQuote(`${remoteUser}:${remoteUser}`)} ${shellQuote(controlDir)} ${shellQuote(workspaceDir)}; fi`,
    'if [ "$installed_bridge_sdk" -eq 1 ]; then',
    `  if id ${shellQuote(remoteUser)} >/dev/null 2>&1; then chown -R ${shellQuote(`${remoteUser}:${remoteUser}`)} ${shellQuote(bridgePackageDir)}; fi`,
    'fi',
    'if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then',
    '  systemctl daemon-reload',
    '  systemctl enable --now pi-bridge.service',
    'else',
    `  pkill -f ${shellQuote(bridgeScriptPath)} 2>/dev/null || true`,
    `  if id ${shellQuote(remoteUser)} >/dev/null 2>&1 && command -v runuser >/dev/null 2>&1; then`,
    `    nohup runuser -u ${shellQuote(remoteUser)} -- ${shellQuote(bridgeStartPath)} >> ${shellQuote(`${controlDir}/pi-bridge.log`)} 2>&1 &`,
    '  else',
    `    nohup ${shellQuote(bridgeStartPath)} >> ${shellQuote(`${controlDir}/pi-bridge.log`)} 2>&1 &`,
    '  fi',
    'fi',
  );

  if (session.autoRunAgent && !session.bridgeMode) {
    lines.push(
      `printf '%s\\n' launching > ${shellQuote(statusPath)}`,
      'tmux kill-session -t pi-agent 2>/dev/null || true',
      `tmux new-session -d -s pi-agent ${shellQuote(`bash ${runScriptPath} |& tee -a ${logPath}`)}`,
    );
  } else {
    lines.push(`printf '%s\\n' ready > ${shellQuote(statusPath)}`);
  }

  return `${lines.join('\n')}\n`;
}
