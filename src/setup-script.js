import { gzipSync } from 'node:zlib';

function shellQuote(value) {
  const escaped = String(value).replace(/'/g, `'\\''`);
  return `'${escaped}'`;
}

function workspaceRootFor(session, config) {
  return session.remoteWorkspaceRoot || config.remoteWorkspaceDir;
}

function workspaceMainDirFor(session, config) {
  return session.workspaceBridge
    ? session.remoteWorkspaceMainDir || `${workspaceRootFor(session, config).replace(/\/+$/, '')}/main`
    : session.remoteWorkspaceDir || config.remoteWorkspaceDir;
}

function buildRepoLines(session, config) {
  const workspaceRoot = workspaceRootFor(session, config);
  const workspaceDir = workspaceMainDirFor(session, config);

  if (session.repoMode === 'git') {
    const gitArgs = ['git'];

    if (session.repoAuthHeader) {
      gitArgs.push('-c', shellQuote(`http.extraHeader=${session.repoAuthHeader}`));
    }

    const plainClone = [
      ...gitArgs,
      'clone',
      '--depth=1',
      shellQuote(session.repoUrl),
      shellQuote(workspaceDir),
    ].join(' ');

    if (session.workspaceBridge) {
      const fetchBranch = session.branch
        ? `${gitArgs.join(' ')} fetch --prune origin ${shellQuote(session.branch)} || true`
        : `${gitArgs.join(' ')} fetch --prune origin || true`;
      const branchClone = session.branch
        ? [
            ...gitArgs,
            'clone',
            '--depth=1',
            '--branch',
            shellQuote(session.branch),
            shellQuote(session.repoUrl),
            shellQuote(workspaceDir),
          ].join(' ')
        : plainClone;
      return [
        'export GIT_TERMINAL_PROMPT=0',
        `mkdir -p ${shellQuote(workspaceRoot)}`,
        `if [ -d ${shellQuote(`${workspaceDir}/.git`)} ]; then`,
        `  cd ${shellQuote(workspaceDir)}`,
        `  ${fetchBranch}`,
        'else',
        `  rm -rf ${shellQuote(workspaceDir)}`,
        `  ${branchClone} || { rm -rf ${shellQuote(workspaceDir)}; ${plainClone}; }`,
        'fi',
        `cd ${shellQuote(workspaceRoot)}`,
      ];
    }

    const branchClone = session.branch
      ? [
          ...gitArgs,
          'clone',
          '--depth=1',
          '--branch',
          shellQuote(session.branch),
          shellQuote(session.repoUrl),
          shellQuote(workspaceDir),
        ].join(' ')
      : plainClone;
    const fetchCommand = session.branch
      ? `${gitArgs.join(' ')} fetch --prune origin ${shellQuote(session.branch)} || true`
      : `${gitArgs.join(' ')} fetch --prune origin || true`;

    return [
      'export GIT_TERMINAL_PROMPT=0',
      `if [ -d ${shellQuote(`${workspaceDir}/.git`)} ]; then`,
      `  cd ${shellQuote(workspaceDir)}`,
      `  ${fetchCommand}`,
      'else',
      `  if [ -e ${shellQuote(workspaceDir)} ] && [ -n "$(ls -A ${shellQuote(workspaceDir)} 2>/dev/null)" ]; then exit 1; fi`,
      '  cd /',
      `  rm -rf ${shellQuote(workspaceDir)}`,
      `  ${branchClone} || { rm -rf ${shellQuote(workspaceDir)}; ${plainClone}; }`,
      'fi',
      `cd ${shellQuote(workspaceDir)}`,
    ].filter(Boolean);
  }

  const initBranch = shellQuote(session.branch || 'main');
  return [
    `mkdir -p ${shellQuote(workspaceDir)}`,
    `cd ${shellQuote(workspaceDir)}`,
    'if [ ! -d .git ]; then',
    '  git init',
    `  git branch -M ${initBranch} || true`,
    `  printf '# %s\\n' ${shellQuote(session.name)} > README.md`,
    'fi',
  ];
}

function tokenFromRepoAuthHeader(header) {
  const match = String(header || '').match(/^AUTHORIZATION:\s*basic\s+(.+)$/i);
  if (!match) return '';
  try {
    const decoded = Buffer.from(match[1], 'base64').toString('utf8');
    return decoded.startsWith('x-access-token:') ? decoded.slice('x-access-token:'.length) : '';
  } catch {
    return '';
  }
}

function buildInitialGitAuthLines(session, config) {
  const token = tokenFromRepoAuthHeader(session.repoAuthHeader);
  if (!token) return [];
  const remoteHomeDir = config.remoteHomeDir || '/home/root';
  const credentialsPath = `${remoteHomeDir}/.git-credentials`;
  const ghConfigDir = `${remoteHomeDir}/.config/gh`;
  const ghParentDir = `${remoteHomeDir}/.config`;
  const hostsPath = `${ghConfigDir}/hosts.yml`;
  const remoteUser = config.remoteUser || 'root';
  return [
    `mkdir -p ${shellQuote(remoteHomeDir)} ${shellQuote(ghConfigDir)}`,
    `cat > ${shellQuote(credentialsPath)} <<'GITCRED'`,
    `https://x-access-token:${encodeURIComponent(token)}@github.com`,
    'GITCRED',
    `chmod 600 ${shellQuote(credentialsPath)}`,
    `cat > ${shellQuote(hostsPath)} <<'GH_HOSTS'`,
    'github.com:',
    '    user: x-access-token',
    `    oauth_token: ${JSON.stringify(token)}`,
    '    git_protocol: https',
    'GH_HOSTS',
    `chmod 600 ${shellQuote(hostsPath)}`,
    `if id ${shellQuote(remoteUser)} >/dev/null 2>&1; then chown -R ${shellQuote(`${remoteUser}:${remoteUser}`)} ${shellQuote(credentialsPath)} ${shellQuote(ghParentDir)} ${shellQuote(ghConfigDir)} ${shellQuote(hostsPath)}; fi`,
  ];
}

function wrapBase64(value, width = 100000) {
  const lines = [];

  for (let index = 0; index < value.length; index += width) {
    lines.push(value.slice(index, index + width));
  }

  return lines;
}

function buildCompressedFileLines(filePath, content) {
  const normalized = content.replace(/^\s+/gm, '').replace(/\n/g, '');
  const encoded = gzipSync(Buffer.from(normalized, 'utf8'), { level: 9 }).toString('base64');

  return [
    `base64 -d<<'E'|gzip -d>${shellQuote(filePath)}`,
    ...wrapBase64(encoded),
    'E',
  ];
}

